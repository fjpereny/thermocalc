pub fn fluid_state(fluid: &mut Fluid) -> ThermoState {
    ThermoState {
        acentric_factor: fluid.acentric_factor().ok(),
        compressibility: fluid.compressibility().ok(),
        conductivity: fluid.conductivity().ok(),
        critical_density: fluid.critical_density().ok(),
        critical_pressure: fluid.critical_pressure().ok(),
        critical_temperature: fluid.critical_temperature().ok(),
        density: fluid.density().ok(),
        dynamic_viscosity: fluid.dynamic_viscosity().ok(),
        enthalpy: fluid.enthalpy().ok(),
        entropy: fluid.entropy().ok(),
        fundamental_derivative_of_gas_dynamics: fluid.fundamental_derivative_of_gas_dynamics().ok(),
        gibbs_energy: fluid.gibbs_energy().ok(),
        helmholtz_energy: fluid.helmholtz_energy().ok(),
        ideal_gas_enthalpy: fluid.ideal_gas_enthalpy().ok(),
        ideal_gas_entropy: fluid.ideal_gas_entropy().ok(),
        ideal_gas_internal_energy: fluid.ideal_gas_internal_energy().ok(),
        ideal_gas_molar_enthalpy: fluid.ideal_gas_molar_enthalpy().ok(),
        ideal_gas_molar_entropy: fluid.ideal_gas_molar_entropy().ok(),
        ideal_gas_molar_internal_energy: fluid.ideal_gas_molar_internal_energy().ok(),
        ideal_gas_molar_specific_heat_constant_pressure: fluid.ideal_gas_molar_specific_heat().ok(),
        ideal_gas_specific_heat_constant_pressure: fluid.ideal_gas_specific_heat().ok(),
        internal_energy: fluid.internal_energy().ok(),
        isentropic_expansion_coefficient: fluid.isentropic_expansion_coefficient().ok(),
        isothermal_compressibility: fluid.isothermal_compressibility().ok(),
        kinematic_viscosity: fluid.kinematic_viscosity().ok(),
        molar_density: fluid.molar_density().ok(),
        molar_enthalpy: fluid.molar_enthalpy().ok(),
        molar_entropy: fluid.molar_entropy().ok(),
        molar_gibbs_energy: fluid.molar_gibbs_energy().ok(),
        molar_helmholtz_energy: fluid.molar_helmholtz_energy().ok(),
        molar_internal_energy: fluid.molar_internal_energy().ok(),
        molar_quality: fluid.molar_quality().ok(),
        molar_specific_heat_constant_pressure: fluid.molar_specific_heat().ok(),
        molar_specific_heat_constant_volume: fluid.molar_specific_heat_const_volume().ok(),
        molar_mass: fluid.molar_mass().ok(),
        ozone_depletion_potential: fluid.odp().ok(),
        phase: Some(fluid.phase()),
        phase_id_param: fluid.phase_id_param().ok(),
        prandtl_number: fluid.prandtl().ok(),
        pressure: fluid.pressure().ok(),
        quality: fluid.quality().ok(),
        ratio_of_specific_heats: if fluid.specific_heat().is_ok()
            && fluid.specific_heat_const_volume().is_ok()
        {
            Some(fluid.specific_heat().unwrap() / fluid.specific_heat_const_volume().unwrap())
        } else {
            None
        },
        residual_molar_enthalpy: fluid.residual_molar_enthalpy().ok(),
        residual_molar_entropy: fluid.residual_molar_entropy().ok(),
        residual_molar_gibbs_energy: fluid.residual_molar_gibbs_energy().ok(),
        specific_heat_constant_pressure: fluid.specific_heat().ok(),
        specific_heat_constant_volume: fluid.specific_heat_const_volume().ok(),
        speed_of_sound: fluid.sound_speed().ok(),
        specific_volume: fluid.specific_volume().ok(),
        surface_tension: fluid.surface_tension().ok(),
        tau: fluid.tau().ok(),
        temperature: fluid.temperature().ok(),
        triple_point_pressure: fluid.triple_pressure().ok(),
        triple_point_temperature: fluid.triple_temperature().ok(),
    }
}
