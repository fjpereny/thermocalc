impl From<&ThermoState> for ThermoStateView {
    fn from(state: &ThermoState) -> Self {
        let fmt_opt = |opt: Option<f64>| -> String {
            match opt {
                Some(val) => format!("{:.3}", val),
                None => "UNDEF".to_string(),
            }
        };

        Self {
            acentric_factor: fmt_opt(state.acentric_factor),
            compressibility: fmt_opt(state.compressibility),
            conductivity: fmt_opt(state.conductivity),
            critical_density: fmt_opt(state.critical_density),
            critical_pressure: fmt_opt(state.critical_pressure),
            critical_temperature: fmt_opt(state.critical_temperature),
            density: fmt_opt(state.density),
            dynamic_viscosity: fmt_opt(state.dynamic_viscosity),
            enthalpy: fmt_opt(state.enthalpy),
            entropy: fmt_opt(state.entropy),
            fundamental_derivative_of_gas_dynamics: fmt_opt(
                state.fundamental_derivative_of_gas_dynamics,
            ),
            gibbs_energy: fmt_opt(state.gibbs_energy),
            helmholtz_energy: fmt_opt(state.helmholtz_energy),
            ideal_gas_enthalpy: fmt_opt(state.ideal_gas_enthalpy),
            ideal_gas_entropy: fmt_opt(state.ideal_gas_entropy),
            ideal_gas_internal_energy: fmt_opt(state.ideal_gas_internal_energy),
            ideal_gas_molar_enthalpy: fmt_opt(state.ideal_gas_molar_enthalpy),
            ideal_gas_molar_entropy: fmt_opt(state.ideal_gas_molar_entropy),
            ideal_gas_molar_internal_energy: fmt_opt(state.ideal_gas_molar_internal_energy),
            ideal_gas_molar_specific_heat_constant_pressure: fmt_opt(
                state.ideal_gas_molar_specific_heat_constant_pressure,
            ),
            ideal_gas_specific_heat_constant_pressure: fmt_opt(
                state.ideal_gas_specific_heat_constant_pressure,
            ),
            internal_energy: fmt_opt(state.internal_energy),
            isentropic_expansion_coefficient: fmt_opt(state.isentropic_expansion_coefficient),
            isothermal_compressibility: fmt_opt(state.isothermal_compressibility),
            kinematic_viscosity: fmt_opt(state.kinematic_viscosity),
            molar_density: fmt_opt(state.molar_density),
            molar_enthalpy: fmt_opt(state.molar_enthalpy),
            molar_entropy: fmt_opt(state.molar_entropy),
            molar_internal_energy: fmt_opt(state.molar_internal_energy),
            molar_quality: fmt_opt(state.molar_quality),
            molar_specific_heat_constant_pressure: fmt_opt(
                state.molar_specific_heat_constant_pressure,
            ),
            molar_specific_heat_constant_volume: fmt_opt(state.molar_specific_heat_constant_volume),
            molar_gibbs_energy: fmt_opt(state.molar_gibbs_energy),
            molar_helmholtz_energy: fmt_opt(state.molar_helmholtz_energy),
            molar_mass: fmt_opt(state.molar_mass),
            ozone_depletion_potential: fmt_opt(state.ozone_depletion_potential),

            phase: match state.phase {
                Some(p) => format!("{:?}", p),
                None => "UNDEF".to_string(),
            },

            phase_id_param: fmt_opt(state.phase_id_param),
            prandtl_number: fmt_opt(state.prandtl_number),
            pressure: fmt_opt(state.pressure),
            quality: fmt_opt(state.quality),
            ratio_of_specific_heats: fmt_opt(state.ratio_of_specific_heats),
            residual_molar_enthalpy: fmt_opt(state.residual_molar_enthalpy),
            residual_molar_entropy: fmt_opt(state.residual_molar_entropy),
            residual_molar_gibbs_energy: fmt_opt(state.residual_molar_gibbs_energy),
            specific_heat_constant_pressure: fmt_opt(state.specific_heat_constant_pressure),
            specific_heat_constant_volume: fmt_opt(state.specific_heat_constant_volume),
            speed_of_sound: fmt_opt(state.speed_of_sound),
            specific_volume: fmt_opt(state.specific_volume),
            surface_tension: fmt_opt(state.surface_tension),
            tau: fmt_opt(state.tau),
            temperature: fmt_opt(state.temperature),
            triple_point_pressure: fmt_opt(state.triple_point_pressure),
            triple_point_temperature: fmt_opt(state.triple_point_temperature),
        }
    }
}
